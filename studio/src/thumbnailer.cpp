Thumbnailer::Thumbnailer() : root_(ThumbsRoot()) {}

std::filesystem::path Thumbnailer::ThumbsRoot() const {
  const std::string override = GetEnvStr("K6WP_THUMBS_DIR");
  if (!override.empty()) {
    return std::filesystem::path(override);
  }
  const std::string local = GetEnvStr("LOCALAPPDATA");
  if (!local.empty()) {
    return std::filesystem::path(local) / "K6WP" / "thumbs";
  }
  const std::string profile = GetEnvStr("USERPROFILE");
  if (!profile.empty()) {
    return std::filesystem::path(profile) / "AppData" / "Local" / "K6WP" /
           "thumbs";
  }
  std::error_code ec;
  return std::filesystem::temp_directory_path(ec) / "K6WP" / "thumbs";
}

bool Thumbnailer::EnsureRoot() {
  try {
    std::error_code ec;
    std::filesystem::create_directories(root_, ec);
    if (ec) {
      LogThumbError("cannot create thumbs dir: " + ec.message());
      return false;
    }
    return true;
  } catch (const std::exception& e) {
    LogThumbError(std::string("cannot create thumbs dir: ") + e.what());
    return false;
  }
}

std::string Thumbnailer::CacheKeyHex(const std::filesystem::path& video) {
  try {
    std::error_code ec;
    const std::filesystem::path abs = std::filesystem::absolute(video, ec);
    if (ec) return "";
    // LOW-4 fast path: mtime/size from the library.json index (zero per-
    // video stats on a hit). The grid calls this per item per refresh, so
    // 100 items cost ~1 hot stat of library.json + map lookups instead of
    // 300 cold stats of the videos.
    LibraryMetaEntry meta;
    if (LookupLibraryMeta(abs.u8string(), &meta)) {
      return k6wp::Sha1Hex(ThumbCacheKeyMaterial(abs, meta.size, meta.mtime,
                                                 kThumbCacheVersion));
    }
    if (!std::filesystem::is_regular_file(abs, ec) || ec) return "";
    const std::uint64_t size =
        static_cast<std::uint64_t>(std::filesystem::file_size(abs, ec));
    if (ec) return "";
    const auto mtime = std::filesystem::last_write_time(abs, ec);
    if (ec) return "";
    const long long mtime_count =
        static_cast<long long>(mtime.time_since_epoch().count());
    return k6wp::Sha1Hex(ThumbCacheKeyMaterial(abs, size, mtime_count,
                                               kThumbCacheVersion));
  } catch (...) {
    return "";
  }
}

std::filesystem::path Thumbnailer::GetThumb(
    const std::filesystem::path& video) {
  try {
    const std::string key = CacheKeyHex(video);
    if (key.empty()) {
      LogThumbError("cannot stat input (missing?): " + video.u8string());
      return {};
    }
    const auto thumb = root_ / (key + ".jpg");

    // Cache hit: non-empty JPEG already on disk.
    std::error_code ec;
    if (std::filesystem::is_regular_file(thumb, ec) && !ec &&
        std::filesystem::file_size(thumb, ec) > 0 && !ec) {
      return thumb;
    }

    if (!EnsureRoot()) return {};

    std::error_code aec;
    const auto abs = std::filesystem::absolute(video, aec);
    if (aec) {
      LogThumbError("cannot resolve input: " + video.u8string());
      return {};
    }
    if (!GenerateTo(abs, thumb)) {
      LogThumbError("ffmpeg failed for: " + video.u8string());
      // Remove a partial output so the next call retries instead of
      // treating a 0-byte file as a hit (hit path requires size > 0).
      std::error_code dec;
      std::filesystem::remove(thumb, dec);
      return {};
    }
    return thumb;
  } catch (const std::exception& e) {
    LogThumbError(std::string("internal error: ") + e.what());
    return {};
  } catch (...) {
    LogThumbError("internal error (unknown)");
    return {};
  }
}

std::filesystem::path Thumbnailer::CachedThumb(
    const std::filesystem::path& video) const {
  try {
    const std::string key = CacheKeyHex(video);
    if (key.empty()) return {};
    const auto thumb = root_ / (key + ".jpg");
    std::error_code ec;
    if (std::filesystem::is_regular_file(thumb, ec) && !ec &&
        std::filesystem::file_size(thumb, ec) > 0 && !ec) {
      return thumb;
    }
    return {};
  } catch (...) {
    return {};
  }
}

std::filesystem::path Thumbnailer::FfmpegPath() {
  // Centralized in k6wp_shared (env override + flat + build + vendored).
  // Never throws; caller checks existence.
  try {
    return ::k6wp::FindFfmpeg();
  } catch (...) {
    return {};
  }
}

bool Thumbnailer::GenerateTo(const std::filesystem::path& video,
                             const std::filesystem::path& thumb) {
  try {
    std::error_code ec;
    if (!std::filesystem::is_regular_file(video, ec) || ec) return false;
    const auto ffmpeg = FfmpegPath();
    if (ffmpeg.empty() || !std::filesystem::exists(ffmpeg, ec) || ec) {
      return false;
    }

    // MED-13: safe seek. Probe duration once (ffprobe); on ANY probe
    // failure fall back to -ss 0 (frame 0 always exists) instead of the
    // old fixed -ss 1, which fails on videos shorter than 1s.
    double duration = 0.0;
    {
      FfprobeHelper probe;
      VideoMetadata meta;
      if (probe.Probe(video, meta)) duration = meta.duration;
    }
    const double seek = SafeSeekSeconds(duration);

    // MED-13: aspect-preserving scale+pad (see BuildThumbCommand) — the
    // old fixed -s 320x180 stretched non-16:9 sources.
    const std::wstring cmd = BuildThumbCommand(
        ffmpeg, video, thumb, seek, kThumbWidth, kThumbHeight, kJpegQuality);

    STARTUPINFOW si{};
    si.cb = sizeof(si);
    si.dwFlags = STARTF_USESTDHANDLES;

    // Redirect stdout+stderr to NUL to prevent pipe-buffer deadlock.
    HANDLE nul = CreateFileW(L"NUL", GENERIC_WRITE, FILE_SHARE_READ, nullptr,
                             OPEN_EXISTING, 0, nullptr);
    if (nul == INVALID_HANDLE_VALUE) return false;
    si.hStdOutput = nul;
    si.hStdError = nul;
    si.hStdInput = GetStdHandle(STD_INPUT_HANDLE);

    PROCESS_INFORMATION pi{};

    // CreateProcessW requires a mutable command-line buffer.
    std::vector<wchar_t> cmd_buf(cmd.begin(), cmd.end());
    cmd_buf.push_back(L'\0');

    const BOOL ok = CreateProcessW(
        ffmpeg.wstring().c_str(),  // lpApplicationName (null-terminated path)
        cmd_buf.data(),            // lpCommandLine (mutable)
        nullptr, nullptr,          // default security
        TRUE,                      // bInheritHandles (for NUL redirect)
        CREATE_NO_WINDOW,          // no console window
        nullptr, nullptr,          // inherit env, inherit cwd
        &si, &pi);

    CloseHandle(nul);
    if (!ok) return false;

    CloseHandle(pi.hThread);

    const DWORD wait = WaitForSingleObject(pi.hProcess, kFfmpegTimeoutMs);
    if (wait == WAIT_TIMEOUT) {
      TerminateProcess(pi.hProcess, 1);
      CloseHandle(pi.hProcess);
      return false;
    }

    DWORD exit_code = 1;
    GetExitCodeProcess(pi.hProcess, &exit_code);
    CloseHandle(pi.hProcess);

    return exit_code == 0 && std::filesystem::is_regular_file(thumb, ec) &&
           !ec && std::filesystem::file_size(thumb, ec) > 0 && !ec;
  } catch (...) {
    return false;
  }
}

