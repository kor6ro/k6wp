// MSVC-safe getenv wrapper (windows.h-free; _dupenv_s lives in <cstdlib>).
std::string GetEnvStr(const char* name) {
  char* buf = nullptr;
  std::size_t len = 0;
  if (_dupenv_s(&buf, &len, name) != 0 || buf == nullptr) {
    return "";
  }
  std::string value(buf);
  std::free(buf);
  return value;
}

