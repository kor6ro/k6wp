// Unit tests for studio/src/thumbnailer.cpp pure helpers (MED-13).
// No external test framework: plain asserts with a pass/fail counter,
// same style as tests/config_test.cpp. Exit code 0 = all pass.
//
// Includes thumbnailer.cpp directly (occlusion_test-style single-TU
// pattern) so the anonymous-namespace helpers are reachable without
// exposing them in the header.
//
// Also exposes a QA mode: `thumbnailer_test --gen <video>` runs the real
// Thumbnailer::GetThumb() and prints GEN-OK <thumb-path> / GEN-FAIL, used
// by the MED-13 QA evidence (0.5s + 4:3 fixtures, missing-ffmpeg failure).
